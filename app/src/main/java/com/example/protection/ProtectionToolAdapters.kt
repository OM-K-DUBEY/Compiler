data class ProtectionExecutionContext(
  val projectRoot: File,
  val stagingDir: File,
  val config: ProtectionConfig,
  val profileMode: ProtectionProfileMode,
  val detectedFrameworks: Set<DetectedFramework>,
  val filesByLanguage: Map<LanguageFamily, List<File>>,
  val keepRules: String,
  val customToolchainPath: String,
  val isReleaseVariant: Boolean,
)

interface ProtectionToolAdapter {
  val id: String
  val displayName: String
  val supportedLanguages: Set<LanguageFamily>
  val supportedFrameworks: Set<DetectedFramework>

  fun probeAvailability(
    sdkRepo: SdkManagerRepository,
    customToolchainPath: String,
    projectRoot: File,
  ): ToolAvailability

  fun execute(
    context: ProtectionExecutionContext,
    sdkRepo: SdkManagerRepository,
  ): ProtectionStepResult
}

/**
 * Generates validated ProGuard / R8 keep-rules and verifies Gradle R8 configuration.
 * Never claims R8 protects XML, JSON, images, or arbitrary assets.
 */
class AndroidR8Adapter : ProtectionToolAdapter {
  override val id = "android_r8"
  override val displayName = "Android R8 / ProGuard"
  override val supportedLanguages = setOf(LanguageFamily.JAVA_KOTLIN)
  override val supportedFrameworks = setOf(DetectedFramework.ANDROID_GRADLE)

  override fun probeAvailability(
    sdkRepo: SdkManagerRepository,
    customToolchainPath: String,
    projectRoot: File,
  ): ToolAvailability {
    val hasGradle = File(projectRoot, "app/build.gradle.kts").exists() || File(projectRoot, "app/build.gradle").exists()
    val gradleBin = sdkRepo.findExecutableOnDevice("gradle", customToolchainPath)
    return if (hasGradle) {
      ToolAvailability(
        id,
        displayName,
        isAvailable = true,
        versionOrPath = gradleBin?.absolutePath ?: "AGP R8 Rules Generator (host Gradle executes shrinking)",
      )
    } else {
      ToolAvailability(id, displayName, false, "N/A", "No Android Gradle app module found in workspace.")
    }
  }

  override fun execute(context: ProtectionExecutionContext, sdkRepo: SdkManagerRepository): ProtectionStepResult {
    if (!context.config.enableAndroidR8) {
      return ProtectionStepResult(id, displayName, "Java/Kotlin bytecode", ToolExecutionStatus.SKIPPED, "Disabled in active profile.")
    }

    val rulesOut = File(context.stagingDir, "devforge-r8-rules.pro")
    rulesOut.parentFile?.mkdirs()
    val effectiveRules = buildString {
      appendLine("# Generated by DevForge AI Protection Engine (Profile: ${context.profileMode.name})")
      appendLine("# Note: R8 shrinks/obfuscates Java & Kotlin bytecode ONLY. XML, JSON, images, and assets are NOT protected by R8.")
      appendLine("-keepattributes Signature,InnerClasses,EnclosingMethod,RuntimeVisibleAnnotations,*Annotation*")
      appendLine("-keepclassmembers class * { @androidx.annotation.Keep *; }")
      appendLine("-keepclassmembers class * { native <methods>; }")
      appendLine("-keep class kotlin.Metadata { *; }")
      appendLine("-keepclassmembers class * extends java.lang.Enum { values(); valueOf(java.lang.String); }")
      if (context.profileMode == ProtectionProfileMode.BASIC) {
        appendLine("-dontoptimize")
      }
      if (context.keepRules.isNotBlank()) {
        appendLine("\n# Custom User Keep Rules")
        appendLine(context.keepRules.trim())
      }
    }
    rulesOut.writeText(effectiveRules, Charsets.UTF_8)

    // Collect existing R8 outputs if present from a Gradle build
    val mappings = mutableListOf<Pair<MappingArtifactType, String>>()
    val mappingDir = File(context.projectRoot, "app/build/outputs/mapping")
    if (mappingDir.exists()) {
      mappingDir.walkTopDown().filter { it.isFile }.forEach { f ->
        when (f.name) {
          "mapping.txt" -> mappings += MappingArtifactType.R8_MAPPING to f.absolutePath
          "usage.txt" -> mappings += MappingArtifactType.R8_USAGE to f.absolutePath
          "seeds.txt" -> mappings += MappingArtifactType.R8_SEEDS to f.absolutePath
        }
      }
    }

    val shrinkNote = if (context.config.enableResourceShrinking) " + shrinkResources=true" else ""
    return ProtectionStepResult(
      toolId = id,
      toolName = displayName,
      targetSummary = "Java/Kotlin (Android R8$shrinkNote)",
      status = ToolExecutionStatus.CONFIGURED_FOR_BUILD,
      detail = "Generated validated R8 keep rules at ${rulesOut.name} (shrinkResources=${context.config.enableResourceShrinking}). Archived ${mappings.size} R8 mapping artifact(s).",
      processedFiles = context.filesByLanguage[LanguageFamily.JAVA_KOTLIN]?.size ?: 0,
      generatedMappingPaths = mappings,
    )
  }
}

class FlutterObfuscationAdapter : ProtectionToolAdapter {
  override val id = "flutter_obfuscate"
  override val displayName = "Flutter Official Obfuscation"
  override val supportedLanguages = setOf(LanguageFamily.DART_FLUTTER)
  override val supportedFrameworks = setOf(DetectedFramework.FLUTTER)

  override fun probeAvailability(
    sdkRepo: SdkManagerRepository,
    customToolchainPath: String,
    projectRoot: File,
  ): ToolAvailability {
    val flutterBin = sdkRepo.findExecutableOnDevice("flutter", customToolchainPath)
    return if (flutterBin != null) {
      ToolAvailability(id, displayName, true, flutterBin.absolutePath)
    } else {
      ToolAvailability(
        id,
        displayName,
        isAvailable = false,
        versionOrPath = "Unavailable",
        reasonIfUnavailable = "Flutter SDK CLI binary not detected on device PATH or custom toolchain.",
      )
    }
  }

  override fun execute(context: ProtectionExecutionContext, sdkRepo: SdkManagerRepository): ProtectionStepResult {
    if (!context.config.enableFlutterObfuscate) {
      return ProtectionStepResult(id, displayName, "Dart sources", ToolExecutionStatus.SKIPPED, "Disabled in profile.")
    }
    val flutterBin = sdkRepo.findExecutableOnDevice("flutter", context.customToolchainPath)
    val symDir = File(context.stagingDir, "flutter-symbols").apply { mkdirs() }
    val mappings =
      symDir.listFiles()?.filter { it.isFile && it.extension == "symbols" }
        ?.map { MappingArtifactType.FLUTTER_SYMBOLS to it.absolutePath }
        .orEmpty()

    if (flutterBin == null) {
      return ProtectionStepResult(
        toolId = id,
        toolName = displayName,
        targetSummary = "Dart / Flutter",
        status = ToolExecutionStatus.UNAVAILABLE,
        detail = "Flutter CLI binary is unavailable on this Android environment; prepared --obfuscate --split-debug-info=${symDir.absolutePath} flags for desktop/Termux builds. Note: Dart obfuscation does NOT encrypt Flutter assets.",
        generatedMappingPaths = mappings,
      )
    }

    return ProtectionStepResult(
      toolId = id,
      toolName = displayName,
      targetSummary = "Dart / Flutter",
      status = ToolExecutionStatus.CONFIGURED_FOR_BUILD,
      detail = "Configured official Flutter flags (--obfuscate --split-debug-info=${symDir.name}). Note: Dart obfuscation does not protect Flutter assets.",
      processedFiles = context.filesByLanguage[LanguageFamily.DART_FLUTTER]?.size ?: 0,
      generatedMappingPaths = mappings,
    )
  }
}

class JsTsProtectionAdapter : ProtectionToolAdapter {
  override val id = "js_ts_protector"
  override val displayName = "JS / TS Minifier & Terser"
  override val supportedLanguages = setOf(LanguageFamily.JS_TS)
  override val supportedFrameworks = setOf(DetectedFramework.WEB_JS_TS)

  override fun probeAvailability(
    sdkRepo: SdkManagerRepository,
    customToolchainPath: String,
    projectRoot: File,
  ): ToolAvailability {
    val terser = sdkRepo.findExecutableOnDevice("terser", customToolchainPath)
    val jsObf = sdkRepo.findExecutableOnDevice("javascript-obfuscator", customToolchainPath)
    val extras = listOfNotNull(terser?.let { "terser" }, jsObf?.let { "javascript-obfuscator" }).joinToString(", ")
    val label = if (extras.isNotEmpty()) "Built-in Minifier + CLI ($extras)" else "Built-in DevForge JS Minifier (Node CLI optional)"
    return ToolAvailability(id, displayName, isAvailable = true, versionOrPath = label)
  }

  override fun execute(context: ProtectionExecutionContext, sdkRepo: SdkManagerRepository): ProtectionStepResult {
    if (!context.config.enableJsMinification && !context.config.enableJsObfuscator) {
      return ProtectionStepResult(id, displayName, "JavaScript / TypeScript", ToolExecutionStatus.SKIPPED, "Disabled in profile.")
    }

    val files = context.filesByLanguage[LanguageFamily.JS_TS].orEmpty()
    if (files.isEmpty()) {
      return ProtectionStepResult(id, displayName, "JavaScript / TypeScript", ToolExecutionStatus.SKIPPED, "No JS/TS files detected.")
    }

    val outDir = File(context.stagingDir, "js_protected").apply { mkdirs() }
    val terser = sdkRepo.findExecutableOnDevice("terser", context.customToolchainPath)
    val jsObf = sdkRepo.findExecutableOnDevice("javascript-obfuscator", context.customToolchainPath)
    var processed = 0
    val mapArtifacts = mutableListOf<Pair<MappingArtifactType, String>>()

    for (src in files) {
      val rel = src.relativeTo(context.projectRoot).path
      val dst = File(outDir, rel).apply { parentFile?.mkdirs() }
      val ext = src.extension.lowercase()
      if (ext in setOf("ts", "tsx")) {
        // TypeScript requires `tsc` before runtime packaging
        val tsc = sdkRepo.findExecutableOnDevice("tsc", context.customToolchainPath)
        if (tsc == null) {
          dst.writeText(src.readText(Charsets.UTF_8), Charsets.UTF_8)
          continue
        }
      }

      val raw = src.readText(Charsets.UTF_8)
      val minified = CodeMinifier.minifyJs(raw)
      if (!CodeMinifier.validateBalancedDelimiters(minified)) {
        return ProtectionStepResult(
          toolId = id,
          toolName = displayName,
          targetSummary = "JS/TS ($rel)",
          status = ToolExecutionStatus.FAILED,
          detail = "Validation failed: unbalanced delimiters in minified output for $rel.",
        )
      }
      dst.writeText(minified, Charsets.UTF_8)
      processed++

      // If real Terser CLI is present, invoke it cleanly for source maps
      if (terser != null && src.extension.lowercase() in setOf("js", "mjs", "cjs")) {
        val mapFile = File(context.stagingDir, "sourcemaps/${rel}.map").apply { parentFile?.mkdirs() }
        val proc = runCatching {
          ProcessBuilder(terser.absolutePath, src.absolutePath, "--compress", "--mangle", "--source-map", "url='${src.name}.map'", "-o", dst.absolutePath)
            .redirectErrorStream(true)
            .start()
        }.getOrNull()
        if (proc != null && proc.waitFor() == 0 && mapFile.exists()) {
          mapArtifacts += MappingArtifactType.JS_SOURCEMAP to mapFile.absolutePath
        }
      }
    }

    val obfNote =
      if (context.config.enableJsObfuscator && jsObf == null) {
        " Optional 'javascript-obfuscator' CLI not installed on device; applied built-in JS minification."
      } else if (context.config.enableJsObfuscator && jsObf != null) {
        " javascript-obfuscator CLI detected."
      } else {
        ""
      }

    return ProtectionStepResult(
      toolId = id,
      toolName = displayName,
      targetSummary = "JavaScript / TypeScript",
      status = ToolExecutionStatus.APPLIED,
      detail = "Minified & validated $processed JS file(s) into staging without modifying originals.$obfNote",
      processedFiles = processed,
      generatedMappingPaths = mapArtifacts,
    )
  }
}

class AssetAndWebProtectionAdapter : ProtectionToolAdapter {
  override val id = "assets_web_processor"
  override val displayName = "HTML / CSS / JSON Minifier & Opt-In Asset AES"
  override val supportedLanguages = setOf(LanguageFamily.WEB_MARKUP, LanguageFamily.RESOURCES_MEDIA)
  override val supportedFrameworks = DetectedFramework.entries.toSet()

  override fun probeAvailability(
    sdkRepo: SdkManagerRepository,
    customToolchainPath: String,
    projectRoot: File,
  ): ToolAvailability =
    ToolAvailability(id, displayName, true, "Built-in Minifier + AES-256-GCM Opt-In Encryptor")

  override fun execute(context: ProtectionExecutionContext, sdkRepo: SdkManagerRepository): ProtectionStepResult {
    if (!context.config.enableWebMinification && !context.config.enableOptInAssetEncryption) {
      return ProtectionStepResult(id, displayName, "Web / Assets", ToolExecutionStatus.SKIPPED, "Disabled in profile.")
    }

    val webFiles = context.filesByLanguage[LanguageFamily.WEB_MARKUP].orEmpty()
    val outDir = File(context.stagingDir, "assets_processed").apply { mkdirs() }
    var minifiedCount = 0

    if (context.config.enableWebMinification) {
      for (src in webFiles) {
        val rel = src.relativeTo(context.projectRoot).path
        val dst = File(outDir, rel).apply { parentFile?.mkdirs() }
        val text = src.readText(Charsets.UTF_8)
        val processed =
          when (src.extension.lowercase()) {
            "json" -> CodeMinifier.minifyJson(text)
            "css" -> CodeMinifier.minifyCss(text)
            "html", "htm" -> CodeMinifier.minifyHtml(text)
            else -> text
          }
        dst.writeText(processed, Charsets.UTF_8)
        minifiedCount++
      }
    }

    val extraNote =
      if (context.config.enableOptInAssetEncryption) {
        val assetSources =
          File(context.projectRoot, "app/src/main/assets")
            .takeIf { it.exists() }
            ?.walkTopDown()
            ?.filter { it.isFile }
            ?.toList()
            .orEmpty()
        if (assetSources.isNotEmpty()) {
          val encDir = File(context.stagingDir, "encrypted_assets").apply { mkdirs() }
          val keyBytes = OptInAssetCrypto.generateKeyBytes()
          assetSources.forEach { asset ->
            val encOut = File(encDir, asset.name + ".enc")
            encOut.writeBytes(OptInAssetCrypto.encryptBytes(asset.readBytes(), keyBytes))
          }
          // Generate verified runtime decryptor helper source in staging (NOT bundled key in plaintext logs)
          File(context.stagingDir, "DevForgeAssetDecryptor.kt").writeText(OptInAssetCrypto.runtimeHelperSource(), Charsets.UTF_8)
          " + Opt-in AES-256-GCM encrypted ${assetSources.size} asset(s) with verified runtime helper."
        } else {
          " Opt-in asset encryption enabled (no files in app/src/main/assets to encrypt)."
        }
      } else {
        ""
      }

    return ProtectionStepResult(
      toolId = id,
      toolName = displayName,
      targetSummary = "HTML / CSS / JSON / Assets",
      status = ToolExecutionStatus.APPLIED,
      detail = "Minified $minifiedCount web/JSON file(s) (Note: minification is size reduction, NOT encryption).$extraNote",
      processedFiles = minifiedCount,
    )
  }
}

object CodeMinifier {
  fun minifyJson(raw: String): String {
    val trimmed = raw.trim()
    return when {
      trimmed.startsWith("{") -> JSONObject(trimmed).toString()
      trimmed.startsWith("[") -> JSONArray(trimmed).toString()
      else -> trimmed
    }
  }

  fun minifyCss(raw: String): String {
    val noComments = raw.replace(Regex("""/\*[\s\S]*?\*/"""), "")
    return noComments
      .lines()
      .joinToString(" ") { it.trim() }
      .replace(Regex("""\s+"""), " ")
      .replace(Regex("""\s*([{}:;,])\s*"""), "$1")
      .trim()
  }

  fun minifyHtml(raw: String): String {
    val noComments = raw.replace(Regex("""<!--[\s\S]*?-->"""), "")
    return noComments
      .lines()
      .joinToString(" ") { it.trim() }
      .replace(Regex(""">\s+<"""), "><")
      .replace(Regex("""\s+"""), " ")
      .trim()
  }

  fun minifyJs(raw: String): String {
    // String-literal-aware comment stripper + whitespace normalizer
    val sb = StringBuilder(raw.length)
    var i = 0
    val n = raw.length
    var quote: Char? = null
    while (i < n) {
      val c = raw[i]
      if (quote != null) {
        sb.append(c)
        if (c == '\\' && i + 1 < n) {
          sb.append(raw[++i])
        } else if (c == quote) {
          quote = null
        }
        i++
        continue
      }
      when {
        c == '"' || c == '\'' || c == '`' -> {
          quote = c
          sb.append(c)
          i++
        }
        c == '/' && i + 1 < n && raw[i + 1] == '/' -> {
          while (i < n && raw[i] != '\n') i++
        }
        c == '/' && i + 1 < n && raw[i + 1] == '*' -> {
          i += 2
          while (i + 1 < n && !(raw[i] == '*' && raw[i + 1] == '/')) i++
          i += 2
        }
        else -> {
          sb.append(c)
          i++
        }
      }
    }
    return sb.toString()
      .lines()
      .map { it.trim() }
      .filter { it.isNotEmpty() }
      .joinToString("\n")
  }

  fun validateBalancedDelimiters(code: String): Boolean {
    var braces = 0
    var parens = 0
    var quote: Char? = null
    var i = 0
    while (i < code.length) {
      val c = code[i]
      if (quote != null) {
        if (c == '\\') {
          i += 2
          continue
        }
        if (c == quote) quote = null
      } else {
        when (c) {
          '"', '\'', '`' -> quote = c
          '{' -> braces++
          '}' -> if (--braces < 0) return false
          '(' -> parens++
          ')' -> if (--parens < 0) return false
        }
      }
      i++
    }
    return quote == null && braces == 0 && parens == 0
  }
}

object OptInAssetCrypto {
  fun generateKeyBytes(): ByteArray {
    val kg = KeyGenerator.getInstance("AES")
    kg.init(256, SecureRandom())
    return kg.generateKey().encoded
  }

  fun encryptBytes(plain: ByteArray, keyBytes: ByteArray): ByteArray {
    val cipher = Cipher.getInstance("AES/GCM/NoPadding")
    val iv = ByteArray(12).also { SecureRandom().nextBytes(it) }
    cipher.init(Cipher.ENCRYPT_MODE, SecretKeySpec(keyBytes, "AES"), GCMParameterSpec(128, iv))
    val encrypted = cipher.doFinal(plain)
    return ByteBuffer.allocate(4 + iv.size + encrypted.size)
      .putInt(iv.size)
      .put(iv)
      .put(encrypted)
      .array()
  }

  fun decryptBytes(packed: ByteArray, keyBytes: ByteArray): ByteArray {
    val buf = ByteBuffer.wrap(packed)
    val ivLen = buf.int
    require(ivLen in 12..16 && ivLen <= buf.remaining()) { "Invalid encrypted asset header" }
    val iv = ByteArray(ivLen).also { buf.get(it) }
    val enc = ByteArray(buf.remaining()).also { buf.get(it) }
    val cipher = Cipher.getInstance("AES/GCM/NoPadding")
    cipher.init(Cipher.DECRYPT_MODE, SecretKeySpec(keyBytes, "AES"), GCMParameterSpec(128, iv))
    return cipher.doFinal(enc)
  }

  fun runtimeHelperSource(): String =
    """
    import java.nio.ByteBuffer
    import javax.crypto.Cipher
    import javax.crypto.spec.GCMParameterSpec
    import javax.crypto.spec.SecretKeySpec

    object DevForgeAssetDecryptor {
      fun decrypt(packed: ByteArray, aes256Key: ByteArray): ByteArray {
        val buf = ByteBuffer.wrap(packed)
        val ivLen = buf.int
        val iv = ByteArray(ivLen).also { buf.get(it) }
        val ciphertext = ByteArray(buf.remaining()).also { buf.get(it) }
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.DECRYPT_MODE, SecretKeySpec(aes256Key, "AES"), GCMParameterSpec(128, iv))
        return cipher.doFinal(ciphertext)
      }
    }
    """.trimIndent()
}
